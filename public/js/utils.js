  showToast(message, type = 'success', duration = 3500) {
    const container = document.getElementById('toast-container');
    if (!container) return;
    const toast = document.createElement('div');
    const iconMap = { success: '✓', error: '✕', info: 'ⓘ' };
    toast.className = `toast toast-${type}`;
    toast.innerHTML = `<span style="font-size:15px;font-weight:700">${iconMap[type] || '•'}</span><span>${message}</span>`;
    container.appendChild(toast);
    setTimeout(() => {
      toast.classList.add('fadeOut');
      setTimeout(() => toast.remove(), 300);
    }, duration);
  },

  openModal(html) {
    const overlay = document.getElementById('modal-overlay');
    if (overlay._closeHandler) {
      overlay.removeEventListener('click', overlay._closeHandler);
    }
    overlay.innerHTML = html;
    overlay.classList.remove('hidden');
    overlay._closeHandler = (e) => {
      if (e.target === overlay) this.closeModal();
    };
    overlay.addEventListener('click', overlay._closeHandler);
  },

  closeModal() {
    const overlay = document.getElementById('modal-overlay');
    if (overlay._closeHandler) {
      overlay.removeEventListener('click', overlay._closeHandler);
      overlay._closeHandler = null;
    }
    overlay.classList.add('hidden');
    overlay.innerHTML = '';
  },

  escapeHtml(str) {
    if (!str) return '';
    return str.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#039;');
  },
